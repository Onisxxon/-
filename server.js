const express = require('express');
const path = require('path');
const app = express();
const mysql = require('mysql2');
const PORT = 3000;


app.use(express.static(__dirname));


app.use(express.json());
app.use(express.urlencoded({ extended: true }));
app.use(express.static(path.join(__dirname, 'public')));

const db = mysql.createConnection({
    host: 'localhost',
    user: 'root',      
    password: '1111',  
    database: 'isit_db'
});

db.connect((err) => {
    if (err) {
        console.error('Ошибка подключения к MySQL:', err.message);
    } else {
        console.log('🚀 Подключение к MySQL Workbench успешно!');
    }
});

app.post('/api/callback', (req, res) => {
    const { name, phone } = req.body;
    const sql = 'INSERT INTO callback_requests (name, phone) VALUES (?, ?)';
    
    db.query(sql, [name, phone], (err, result) => {
        if (err) {
            console.error(err);
            return res.status(500).json({ success: false, message: 'Ошибка базы данных' });
        }
        res.json({ success: true, message: 'Заявка на звонок сохранена!' });
    });
});

// Сохранение вопроса
app.post('/api/question', (req, res) => {
    const { name, phone, email, message } = req.body;
    const sql = 'INSERT INTO question_requests (name, phone, email, message) VALUES (?, ?, ?, ?)';
    
    db.query(sql, [name, phone, email, message], (err, result) => {
        if (err) {
            console.error(err);
            return res.status(500).json({ success: false, message: 'Ошибка базы данных' });
        }
        res.json({ success: true, message: 'Ваш вопрос успешно отправлен!' });
    });
});


app.get('/', (req, res) => {
    res.sendFile(path.join(__dirname, 'index.html'));
});

