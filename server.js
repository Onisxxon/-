app.get('/api/search', (req, res) => {
    const query = req.query.q ? req.query.q.toLowerCase().trim() : '';
    
    // Если запрос пустой, просто отдаем пустой массив
    if (!query) {
        return res.json([]);
    }

    let searchResults = [];

    // 1. Статичные страницы (база для навигации)
    const sitePages = [
        { title: "Главная страница — ООО ИСИТ", excerpt: "Разработка, внедрение и поддержка ПО и комплексных систем.", url: "/index.html", type: "page" },
        { title: "Продукция и решения", excerpt: "Таксофоны, интернет-терминалы, ПО и СКУД.", url: "/product.html", type: "page" },
        { title: "О компании ИСИТ", excerpt: "Информация о компании, история и контакты в Перми.", url: "/about.html", type: "page" },
        { title: "Галерея наших проектов", excerpt: "Фотографии внедренных решений и объектов.", url: "/gallery.html", type: "page" },
        { title: "Услуги компании", excerpt: "Проектирование баз данных, автоматизация и техподдержка.", url: "/uslugi.html", type: "page" },
        { title: "Новости компании", excerpt: "Последние события и обновления систем.", url: "/news.html", type: "page" },
        { title: "О компании ИСИТ",
    excerpt: "ЗАО «Интеллектуальные системы и технологии». Поставки таксофонного оборудования, терминалов, СКУД с 1999 года.",
    url: "/about.html",
    type: "page"
}
    ];

    // Поиск по страницам
    sitePages.forEach(page => {
        if (page.title.toLowerCase().includes(query) || page.excerpt.toLowerCase().includes(query)) {
            searchResults.push(page);
        }
    });

    // 2. Поиск по новостям (безопасный цикл)
    if (Array.isArray(allNewsData)) {
        allNewsData.forEach(news => {
            const content = news.content ? news.content.toLowerCase() : '';
            const title = news.title ? news.title.toLowerCase() : '';
            const excerpt = news.excerpt ? news.excerpt.toLowerCase() : '';

            if (title.includes(query) || excerpt.includes(query) || content.includes(query)) {
                searchResults.push({
                    title: news.title,
                    excerpt: news.excerpt,
                    url: `/news.html?articleId=${news.id}`,
                    type: "news"
                });
            }
        });
    }

    res.json(searchResults);
});
